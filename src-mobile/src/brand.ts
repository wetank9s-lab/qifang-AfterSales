/**
 * `brand.ts` —— 员工移动端（含师傅端）的**品牌名唯一出处**（R2.2.1 第十二条）。
 *
 * ===========================================================================
 * 为什么单独一个文件，而不是就地写字面量
 * ===========================================================================
 * 「七方上门服务」这个名字会出现在至少四处：浏览器标签（`document.title`）、
 * `index.html` 的 `<title>`、favicon 旁的站点名（iOS「添加到主屏」）、
 * 登录页大字。任何一处漏改，症状都是"某个页面标题还是旧的"——
 * 而那**不会报错**，只能靠人偶然看见。
 * ⇒ 代码里只认这一个常量；`index.html` 是静态文件，由
 *   `scripts/verify-brand-consistency.mjs` 做一致性核对（两处漂移 ⇒ 门禁红）。
 *
 * ===========================================================================
 * 边界：客户 H5 **不**用这个名字
 * ===========================================================================
 * 客户 H5 的品牌名是**可发布配置**（`page_theme_releases` 里的 `brand.name`，
 * 当前为「四川七方连锁售后服务平台」），由门店自己在后台发布页维护。
 * 2026-11-18 用户裁决：本轮**只改员工端 + 师傅端**，客户 H5 不动 ——
 * 客户看到的是「报修 / 查进度」，不是公司品牌；而动已发布快照等于改线上
 * 客户可见内容，超出本轮授权。
 */
export const MOBILE_BRAND = '七方上门服务';

/**
 * 登录页的大标题（R2.2.1 §三：**固定**为「七方上门服务系统」）。
 *
 * ⚠️ 为什么不是把 `MOBILE_BRAND` 直接改成这个：
 *    `MOBILE_BRAND` 同时是浏览器标签与"添加到主屏"后的图标名，
 *    那一处要短（iOS 主屏名超过 ~6 个汉字会被截断成「七方上门服…」）。
 *    ⇒ 站名短、登录页标题长，是**两个用途**，各留一个常量。
 *    两者都只在本文件出现，任何一处改动仍需过 `verify-brand-consistency.mjs`。
 */
export const MOBILE_BRAND_FULL = '七方上门服务系统';

/** 浏览器标签格式：子页面「页面名 · 品牌名」，根页面只显示品牌名 */
export function pageTitle(page?: string): string {
  const p = (page ?? '').trim();
  if (!p || p === MOBILE_BRAND) return MOBILE_BRAND;
  return `${p} · ${MOBILE_BRAND}`;
}
