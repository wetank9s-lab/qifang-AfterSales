import { belongsTo, CREATED_AT_COLUMN, defineAppCollection, int, json, str, ts } from './_helpers';

/**
 * exportAudits —— 导出审计（**只记事实，不记数据本体**）
 *
 * =============================================================================
 * 为什么需要它（Phase 9 / D3 闭合的配套件）
 * =============================================================================
 *
 * Phase 9 把「导出」定义成一条**独立的高风险数据出境路径**：
 *
 *     svc:exportTickets → 仅 hq_admin → 固定脱敏 → CSV injection 防护 → **导出审计**
 *
 * 一个"可以批量把客户数据带走"的能力，如果**事后无法回答"谁在什么时候带走了多少条"**，
 * 那么它的权限设计再正确也只是"事前"的一半。审计就是那事后的一半。
 *
 * -----------------------------------------------------------------------------
 * ⚠️ 为什么**不**复用 `ticket_events`（这是设计这个表时唯一真正的分岔）
 * -----------------------------------------------------------------------------
 * `ticket_events.ticket_id` 是 `allowNull: false` —— 那是它作为"工单时间线"的
 * **完整性约束**：一条事件必须能回答"它属于哪张工单"。
 *
 * 而"导出"在语义上**不属于任何一张工单**：一次导出可能覆盖窗口内 5000 张工单。
 * 于是只有两条路，都不可取：
 *   · 放宽 `ticket_id` 为可空 ⇒ 牺牲事件表最核心的约束，只为塞进一种异类记录；
 *   · 给被导出的**每一张**工单各写一条事件 ⇒ 5000 条事件只为记录"有人导了一次表"，
 *     既污染业务时间线，又把一次操作放大成 5000 次写入。
 *
 * ⇒ 单开一张表。**跨工单的操作就该记在跨工单的表里。**
 *
 * -----------------------------------------------------------------------------
 * 🔴 只记"必要事实"——这张表的字段清单是**经过收敛的**，不要随手加列
 * -----------------------------------------------------------------------------
 * 用户 2026-09-26 的原话：**"不要把导出的客户手机号或整份 CSV 内容再塞进
 * TicketEvent 来『审计导出』，否则反而制造第二份敏感数据副本。"**
 *
 * 这条纪律**同样适用于本表**（它只是把 TicketEvent 换成了另一张表，泄漏面不会因此变小）：
 *
 *   ✅ 记：操作者（id / username / 角色）、导出时刻、筛选与日期范围、
 *          导出条数、requestId、接口版本、**列名清单**
 *   🔴 不记：任何**被导出的值**（手机号、客户姓名、报修内容…）、整份 CSV 正文
 *
 * 为什么"列名清单"可以记而"列值"不可以：列名回答的是"这次导出了哪些字段"
 * （安全评审需要它 —— 能看出是否有人悄悄扩大了导出面），而它**本身不是业务数据**，
 * 不构成第二份敏感副本。边界判据是"**是否含客户/业务数据**"，不是"是否来自导出流程"。
 *
 * -----------------------------------------------------------------------------
 * 其它约束
 * -----------------------------------------------------------------------------
 *  · **只追加，不修改、不删除**（与 ticket_events 同纪律）：审计记录一旦可改，
 *    它就不再是审计。
 *  · `row_count` 记的是**成功写入 CSV 的条数**；被拒绝/失败的导出**不写本表**
 *    （不伪造成功审计 —— 门禁对这条有断言）。
 *  · 时间戳列名必须用 `CREATED_AT_COLUMN`（NocoBase 注入的是 camelCase `createdAt`，
 *    经 `defineAppCollection` 的 `underscored: true` 落库为 `created_at`）。
 */
export default defineAppCollection({
  name: 'exportAudits',
  title: '导出审计',
  fields: [
    /**
     * 导出通道 —— 目前恒为 `svc:exportTickets`。
     *
     * 留成字段而不是常量，是为了将来真的出现第二条受支持出口时，
     * 审计里能**一眼分辨**是哪个通道发生的，而不是靠时间戳去猜。
     */
    str('channel', '导出通道', {
      length: 32,
      allowNull: false,
      defaultValue: 'svc:exportTickets',
      comment: '唯一受支持出口 svc:exportTickets（D3 冻结）；此列便于将来多通道时区分',
    }),
    /**
     * 导出引擎版本 —— 脱敏/防注入规则的版本号（`export-service.ts` 的常量）。
     *
     * 为什么审计要记"规则版本"：安全规则会演进（今天脱敏 `138****8000`，
     * 明天可能连姓名一起脱敏）。只记"导出了 5000 条"而不记"按哪版规则导的"，
     * 事后就无法判断某次历史导出**当时**是否符合**当时**的规则。
     */
    str('engine_version', '导出规则版本', {
      length: 32,
      allowNull: true,
      comment: 'export-service.ts 的 EXPORT_ENGINE_VERSION；用于事后核对"按哪版规则导出"',
    }),

    // ---------------- 操作者 ----------------
    // 与 ticket_events 的 operator_user_id 同口径（belongsTo users，留关联便于后台点进去看人）
    belongsTo('operator_user', '操作人', 'users', 'operator_user_id', {
      allowNull: true,
      comment: '导出必然由已登录用户发起；留可空仅为兼容用户被删除后的历史记录',
    }),
    str('operator_username', '操作者账号', {
      length: 64,
      allowNull: true,
      comment: '快照：用户被改名/删除后，审计仍能回答"当时是谁"',
    }),
    str('operator_roles', '操作者角色', {
      length: 128,
      allowNull: true,
      comment: '逗号分隔的业务角色快照；用于回答"这次导出以什么身份发生"',
    }),

    // ---------------- 事实 ----------------
    ts('exported_at', '导出时刻', {
      allowNull: false,
      comment: '业务时刻（与 created_at 同值但语义明确：这是"数据出境"发生的时间）',
    }),
    json('filter_json', '筛选与日期范围', {
      allowNull: true,
      comment:
        '仅筛选条件与日期窗口（from/to/storeId/ticketType/serviceMode/ratingMin）。' +
        '⚠️ 绝不含任何被导出单元格的值 —— 审计记"范围"，不记"内容"',
    }),
    int('row_count', '导出条数', {
      allowNull: false,
      defaultValue: 0,
      comment: '成功写入 CSV 的条数；被拒绝/失败的操作不写本表（不伪造成功审计）',
    }),
    json('columns_json', '导出字段清单', {
      allowNull: true,
      comment:
        '列名清单（不是列值）：安全评审需要它来发现"是否有人悄悄扩大了导出面"。' +
        '列名本身不含客户数据，故不构成第二份敏感副本',
    }),
    str('request_id', '请求号', {
      length: 64,
      allowNull: true,
      comment: '与链路日志对齐，回答"这一次导出"具体是哪一笔请求',
    }),
  ],
  indexes: [
    // 后台按时间倒序看"最近谁导了什么"
    { fields: ['exported_at'] },
    // 按人追溯
    { fields: ['operator_user_id'] },
    { fields: [CREATED_AT_COLUMN] },
  ],
});
