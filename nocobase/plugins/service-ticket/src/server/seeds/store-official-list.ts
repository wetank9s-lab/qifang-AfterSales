/**
 * **可落库**的更新：`code → { name, address }`。
 *
 * ⚠️ 只有 `status === 'confirmed'` 的条目会出现在这里 ——
 *    这是"不得猜测绑定"在代码层面的落点：待核对的条目**结构上无法**被写入。
 * ⚠️ 这里**不含** `contact_phone`：用户尚未提供电话号码，
 *    任何一个已有的有效联系方式都**不得被覆盖**（本文件连写它的能力都没有）。
 */
export const CONFIRMED_STORE_PROFILE: Record<string, { name: string; address: string }> =
  Object.fromEntries(
    OFFICIAL_STORE_RECORDS.filter((r) => r.status === 'confirmed' && r.code).map((r) => [
      r.code as string,
      { name: r.name, address: r.address },
    ]),
  );

/** 待核对清单（供报告与页面提示；**不落库**） */
export const PENDING_STORE_RECORDS: OfficialStoreRecord[] = OFFICIAL_STORE_RECORDS.filter(
  (r) => r.status === 'pending',
);

/** 用户提供的总条数（离线断言用；防止有人"顺手少写一条"） */
export const OFFICIAL_STORE_RECORD_COUNT = OFFICIAL_STORE_RECORDS.length;

/**
 * 审计记录写入 `service_settings` 的 key。
 *
 * 为什么要有它：用户要求本次操作**可审计、可复核**。
 * 光有代码与文档不够 —— 那一侧看不到"这台库**实际**改了哪几行、什么时候改的"。
 * 所以把结论落到库里的一个 key 上（`service_settings` 是现成的 key/value 表，
 * 不必为此新建表）。
 */
export const STORE_PROFILE_AUDIT_KEY = 'store.profile.official-list.audit';

/** 生成审计载荷（迁移与门禁共用同一份构造逻辑，避免两处漂移） */
export function buildStoreProfileAudit(appliedAt: string): Record<string, unknown> {
  return {
    source: 'user-provided 2026-10-10',
    applied_at: appliedAt,
    total_provided: OFFICIAL_STORE_RECORDS.length,
    applied: OFFICIAL_STORE_RECORDS.filter((r) => r.status === 'confirmed').map((r) => ({
      code: r.code,
      name: r.name,
      address: r.address,
      evidence: r.evidence,
    })),
    pending: PENDING_STORE_RECORDS.map((r) => ({ name: r.name, address: r.address, reason: r.evidence })),
    /** 未提供资料的门店（用户说"剩余五家未提供"；实际数量以库为准，见门禁） */
    note:
      'contact_phone 一律保持 NULL（用户未提供电话，不生成虚假号码）；' +
      'pending 条目**不得**猜测绑定，需用户给出 code 或确认后另行落库',
  };
}
